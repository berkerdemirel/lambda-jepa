"""E24 wave-1 dose derivation (D-070): from the wave-0 formation-state pulls
(results/diag/e24_pull.csv, state=ckpt) derive per-cell nominal weights for the 16-point
share lattice per frame — w_i = s_i · T / g_i with T = the frame's certified total realized
pull (Σ w·g at formation) held invariant. Emits results/diag/e24_wave1_doses.csv + the
launcher slurm/e24_wave1.sh (chained 8h links per cell, share logger on from birth).
s_h = 0 cells run h_lamb = 0 exactly (term computed, zero-weighted — zonly RNG parity)."""
import csv
import os
import stat

ROOT = "/nfs/scistore19/locatgrp/bdemirel/ssl_project"
SH = [(0, 0.0), (1, 0.03), (2, 0.10), (3, 0.25)]
R = [("a", 0.25), ("b", 0.40), ("c", 0.55), ("d", 0.70)]
FRAMES = {
    "toy_Llr": dict(frame="toy_vits8", extra="method.lr=5e-4", links=2, nc=10),
    "in100_d256": dict(frame="in100_vits16", extra="num_classes=100", links=3, nc=100),
}
TERMS = {"inv": "w_inv", "moment_kl": "w_floor", "h_moment_kl": "h_lamb"}


def main():
    g, T = {}, {}
    for r in csv.DictReader(open(f"{ROOT}/results/diag/e24_pull.csv")):
        if r["state"] == "ckpt":
            g[(r["label"], r["term"])] = float(r["g_enc"])
            T[r["label"]] = float(r["wg_total"])
    rows, lines = [], ["#!/bin/bash", "# E24 wave 1 — generated by e24_doses.py; 32 cells,",
                       "# chained 8h links (resume-safe), share logger every epoch.", ""]
    for label, fr in FRAMES.items():
        for hi, sh in SH:
            for ri, r in R:
                s_z, s_inv = r * (1 - sh), (1 - r) * (1 - sh)
                w_inv = s_inv * T[label] / g[(label, "inv")]
                w_z = s_z * T[label] / g[(label, "moment_kl")]
                w_h = sh * T[label] / g[(label, "h_moment_kl")]
                tag = f"e24s{hi}{ri}"
                rows.append({"frame": label, "tag": tag, "s_h": sh, "r": r,
                             "s_inv": round(s_inv, 4), "s_z": round(s_z, 4),
                             "w_inv": round(w_inv, 3), "w_floor": round(w_z, 3),
                             "h_lamb": round(w_h, 4)})
                ov = (f"method=floorssl frame={fr['frame']} bs=128 tag={tag} "
                      f"share_log_every=1 +method.aug=lejepa +method.V=4 "
                      f"method.head_layers=2 method.expander_dim=256 method.mlp_wd=0.05 "
                      f"{fr['extra']} method.w_inv={w_inv:.3f} "
                      f"method.w_floor={w_z:.3f} method.h_lamb={w_h:.4f}")
                nm = f"e24-{label.split('_')[0]}-{tag}"
                lines.append(f'j=$(sbatch --parsable --begin=now+120 --job-name={nm} '
                             f'slurm/train.sbatch {ov})')
                for _ in range(fr["links"] - 1):
                    lines.append(f'j=$(sbatch --parsable --dependency=afterany:$j '
                                 f'--job-name={nm} slurm/train.sbatch {ov})')
                lines.append(f'echo "{nm} tail=$j"')
    path = f"{ROOT}/results/diag/e24_wave1_doses.csv"
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"[write] {path} ({len(rows)} rows)")
    sh_path = f"{ROOT}/slurm/e24_wave1.sh"
    open(sh_path, "w").write("\n".join(lines) + "\n")
    os.chmod(sh_path, os.stat(sh_path).st_mode | stat.S_IEXEC)
    print(f"[write] {sh_path}")
    for row in rows:
        print(row)


if __name__ == "__main__":
    main()
